// ins-writer.js
// Generates a SHELX .ins file — the actual endpoint of this whole
// pipeline: HKL/CIF in, SHELX structure-solution input out.
//
// SYMM cards and the LATT number follow the standard SHELX convention:
// LATT's sign encodes centrosymmetry (positive = centrosymmetric, SHELX
// adds the inversion center automatically), and its magnitude encodes the
// centering type. Because of that automatic inversion, only ONE operator
// from each {R, -R} pair needs an explicit SYMM card — the proper
// rotations (det(R)=+1); their inversion-related partners (det(R)=-1,
// e.g. mirrors) are generated by SHELX itself. For non-centrosymmetric
// groups there's no such shortcut — every non-identity operator needs its
// own SYMM card.

const LATT_NUMBERS = {
  'P (primitive)': 1,
  I: 2,
  'R (obverse)': 3,
  F: 4,
  A: 5,
  B: 6,
  C: 7,
};

function det3x3(M) {
  return M[0][0] * (M[1][1] * M[2][2] - M[1][2] * M[2][1])
       - M[0][1] * (M[1][0] * M[2][2] - M[1][2] * M[2][0])
       + M[0][2] * (M[1][0] * M[2][1] - M[1][1] * M[2][0]);
}
function isIdentityOp(op) {
  return op.R.every((row, i) => row.every((v, j) => v === (i === j ? 1 : 0)))
    && op.t.every(v => v === 0);
}

// Reduces a twelfths fraction to its simplest form, e.g. 6 -> "1/2".
function formatFraction12(n) {
  const sign = n < 0 ? -1 : 1;
  n = Math.abs(n) % 12;
  if (n === 0) return null;
  function gcd(a, b) { while (b) { [a, b] = [b, a % b]; } return a; }
  const g = gcd(n, 12);
  return `${sign < 0 ? '-' : ''}${n / g}/${12 / g}`;
}

// Formats one Seitz operation as a SHELX-style SYMM line, e.g. "1/2-X,+Y,1/2-Z"
// — a leading fraction comes BEFORE the sign/variable terms, matching the
// conventional SHELX/XPREP output style, rather than appending it at the end.
function formatSymmLine(op) {
  const vars = ['X', 'Y', 'Z'];
  const parts = [0, 1, 2].map(row => {
    let varPart = '';
    for (let col = 0; col < 3; col++) {
      const coeff = op.R[row][col];
      if (coeff === 1) varPart += `+${vars[col]}`;
      else if (coeff === -1) varPart += `-${vars[col]}`;
    }
    const frac = formatFraction12(op.t[row]);
    if (!frac) return varPart || '+0'; // shouldn't normally happen for a valid rotation row
    return frac + varPart;
  });
  return parts.join(',');
}

// Determines the SYMM cards and LATT number for a given Hall symbol.
function getSymmetryCardData(hallSymbol) {
  const { centrosymmetric, latticeTranslations, generators } = parseHallSymbol(hallSymbol);
  const pointGroupOps = generatePointGroupOperators(generators);

  const symmOps = pointGroupOps.filter(op => {
    if (isIdentityOp(op)) return false;
    if (centrosymmetric && det3x3(op.R) !== 1) return false; // auto-generated via the inversion center
    return true;
  });

  const latticeName = latticeTranslationsToName(latticeTranslations);
  const magnitude = LATT_NUMBERS[latticeName];
  if (!magnitude) throw new Error(`Unrecognized lattice type for SHELX LATT card: ${latticeName}`);

  return {
    symmLines: symmOps.map(formatSymmLine),
    lattNumber: centrosymmetric ? magnitude : -magnitude,
  };
}

// Parses a CIF "_chemical_formula_sum" value like "'C24 H20 F6 N4 P'"
// into element/count pairs. Returns null if not found.
function parseChemicalFormula(cifText) {
  const raw = extractCIFTagValue(cifText, '_chemical_formula_sum');
  if (!raw) return null;
  const matches = raw.match(/([A-Z][a-z]?)(\d*)/g) || [];
  return matches
    .filter(m => m.trim() !== '')
    .map(m => {
      const match = m.match(/([A-Z][a-z]?)(\d*)/);
      return { element: match[1], count: match[2] ? parseInt(match[2], 10) : 1 };
    });
}

// Builds the complete .ins file text.
//
// options.settingTransform, if given, means: what's actually measured
// (the native fit, whichever candidate's own systematic absences the raw
// cell/hkl obeys) differs from whichever space-group row was selected on
// the Space Group tab. { matrix, nativeHM, isPurePermutation } — matrix
// transforms the as-measured cell into the selected setting's frame; the
// SAME matrix must go on the HKLF line so SHELXL re-indexes the untouched
// .hkl file to match (see SHELX manual, HKLF instruction: "the cell,
// symmetry and atom coordinates ... must correspond to the indices after
// transformation using this matrix").
function generateInsFile(options) {
  const { title, cell: rawCell, wavelength, hallSymbol, z, formula, composition, esd: rawEsd, settingTransform } = options;

  if (settingTransform && determinant3(settingTransform.matrix) <= 0) {
    throw new Error('setting-transform: refusing to write an HKLF matrix with non-positive determinant');
  }

  const cell = settingTransform ? transformCellParameters(rawCell, settingTransform.matrix) : rawCell;
  // Esds only survive a rigorous transform when it's a pure axis relabeling
  // (no shear) — a genuine shear has no cell covariance matrix available
  // here to propagate them correctly, so they're left as-is (approximate)
  // rather than computed wrong.
  const esd = (settingTransform && settingTransform.isPurePermutation && rawEsd) ? permuteEsds(rawEsd, settingTransform.matrix) : rawEsd;

  const { symmLines, lattNumber } = getSymmetryCardData(hallSymbol);

  const lines = [];
  const titleSuffix = settingTransform ? ` (measured as ${settingTransform.nativeHM.replace(/\s+/g, '')})` : '';
  lines.push(`TITL ${(title || 'structure')}${titleSuffix}`);

  // SHELX only requires whitespace-separated numbers here, but XPREP-style
  // output right-aligns every CELL/ZERR value into a fixed 9-character
  // field so the decimal points of each value line up with its esd
  // directly below it — a, b, c to 4 decimal places, angles (and Z) to 3.
  const pad9 = (s) => String(s).padStart(9);
  const fmtLen = (v) => Number.isFinite(v) ? v.toFixed(4) : '0.0000';
  const fmtAng = (v) => Number.isFinite(v) ? v.toFixed(3) : '0.000';
  lines.push(`CELL${pad9(wavelength ?? 0.71073)}${pad9(fmtLen(cell.a))}${pad9(fmtLen(cell.b))}${pad9(fmtLen(cell.c))}${pad9(fmtAng(cell.alpha))}${pad9(fmtAng(cell.beta))}${pad9(fmtAng(cell.gamma))}`);

  // ZERR Z sd(a) sd(b) sd(c) sd(alpha) sd(beta) sd(gamma) — use the esds
  // that were actually captured from the source file (CIF parentheses,
  // a loaded .ins's own ZERR line, or a .p4p's CELLSD line) where
  // available; fields with no known esd fall back to 0, same as when
  // nothing at all was available.
  const zerrEsds = esd
    ? `${pad9(fmtLen(esd.a))}${pad9(fmtLen(esd.b))}${pad9(fmtLen(esd.c))}${pad9(fmtAng(esd.alpha))}${pad9(fmtAng(esd.beta))}${pad9(fmtAng(esd.gamma))}`
    : `${pad9(fmtLen(0))}${pad9(fmtLen(0))}${pad9(fmtLen(0))}${pad9(fmtAng(0))}${pad9(fmtAng(0))}${pad9(fmtAng(0))}`;
  lines.push(`ZERR${pad9(fmtAng(z ?? 1))}${zerrEsds}`);
  lines.push(`LATT ${lattNumber}`);
  for (const s of symmLines) lines.push(`SYMM ${s}`);

  // An exact whole-cell composition (from a loaded .ins's own SFAC/UNIT)
  // is preferred when available — it's the real atom counts, not a
  // formula-per-unit × Z reconstruction that can drift if Z was estimated
  // or the formula field wasn't filled in.
  if (composition && composition.length > 0) {
    lines.push(`SFAC ${composition.map(c => c.element).join(' ')}`);
    lines.push(`UNIT ${composition.map(c => c.count.toFixed(0)).join(' ')}`);
  } else if (formula && formula.length > 0) {
    lines.push(`SFAC ${formula.map(f => f.element).join(' ')}`);
    lines.push(`UNIT ${formula.map(f => (f.count * (z ?? 1)).toFixed(0)).join(' ')}`);
  } else {
    lines.push('SFAC C H N O ! TODO: replace with the actual elements');
    lines.push('UNIT 1 1 1 1  ! TODO: replace with element counts x Z');
  }

  lines.push('TREF');
  lines.push(settingTransform ? `HKLF 4 1 ${formatHKLFMatrix(settingTransform.matrix)}` : 'HKLF 4');
  lines.push('END');

  return lines.join('\n') + '\n';
}

// Parses a plain-text chemical formula like "C11 H7 N1 S2" (as typed by
// the user, or reconstructed from a CIF value) into element/count pairs.
// Same shape as parseChemicalFormula() above, so both paths feed the same
// downstream logic.
function parseFormulaString(str) {
  const matches = (str || '').match(/([A-Z][a-z]?)(\d*)/g) || [];
  return matches
    .filter(m => m.trim() !== '')
    .map(m => {
      const match = m.match(/([A-Z][a-z]?)(\d*)/);
      return { element: match[1], count: match[2] ? parseInt(match[2], 10) : 1 };
    });
}

function countNonHydrogenAtoms(formula) {
  return formula.filter(f => f.element !== 'H').reduce((sum, f) => sum + f.count, 0);
}

// Standard triclinic cell volume formula (angles in degrees).
function cellVolume(a, b, c, alpha, beta, gamma) {
  const toRad = d => d * Math.PI / 180;
  const [ca, cb, cg] = [Math.cos(toRad(alpha)), Math.cos(toRad(beta)), Math.cos(toRad(gamma))];
  return a * b * c * Math.sqrt(Math.max(0, 1 - ca * ca - cb * cb - cg * cg + 2 * ca * cb * cg));
}

// Rough Z estimate from cell volume and formula, when Z isn't otherwise
// known: ~18 Å³ per non-hydrogen atom is a common rule of thumb for
// organic/small-molecule structures (hydrogens contribute negligibly to
// packing volume). Rounds to the nearest integer, minimum 1 — this is a
// starting estimate for the person to sanity-check, not a substitute for
// knowing Z from the actual experiment.
function estimateZ(volume, formula) {
  const nonH = countNonHydrogenAtoms(formula);
  if (nonH === 0) return null;
  const vf = 18 * nonH;
  return Math.max(1, Math.round(volume / vf));
}
