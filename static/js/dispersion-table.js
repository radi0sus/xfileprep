// f'' per element for a wavelength, or null if no column lies within 1 %.
// Returns { fpp: {El: f''}, column, wavelength, line }.
function dispersionForWavelength(lambda) {
  if (!(lambda > 0)) return null;
  let best = -1, bestRel = Infinity;
  DISPERSION_WAVELENGTHS.forEach((w, i) => { const rel = Math.abs(lambda - w) / w; if (rel < bestRel) { bestRel = rel; best = i; } });
  if (bestRel > 0.01) return null;
  const fpp = { H: 0, D: 0 };
  for (const [el, fdd] of Object.entries(DISPERSION_TABLE)) fpp[el] = fdd[best];
  return { fpp, column: best, wavelength: DISPERSION_WAVELENGTHS[best], line: DISPERSION_LINES[best] };
}
